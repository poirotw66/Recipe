function replaceStepsBlock(source, steps) {
  const lines = steps.map((s) => `- ${s}`).join("\n");
  return source.replace(/^steps:\n(?:- .+\n)+/m, `steps:\n${lines}\n`);
}

function replaceUpdatedAt(source) {
  return source.replace(/^updatedAt: .+$/m, `updatedAt: "${UPDATED_AT}"`);
}

const summary = [];

for (const [slug, config] of Object.entries(BATCH)) {
  const path = join(RECIPES_DIR, `${slug}.md`);
  let source = readFileSync(path, "utf8");
  source = replaceStepsBlock(source, config.steps);
  source = replaceUpdatedAt(source);
  writeFileSync(path, source, "utf8");
  summary.push({ slug, steps: config.steps.length });
}

