function replaceStepsBlock(source, steps) {
  const lines = steps.map((s) => `- ${s}`).join("\n");
  return source.replace(/^steps:\n(?:- .+\n)+/m, `steps:\n${lines}\n`);
}

function replaceUpdatedAt(source) {
  return source.replace(/^updatedAt: .+$/m, `updatedAt: "${UPDATED_AT}"`);
}

